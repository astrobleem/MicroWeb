#!/usr/bin/env python3
"""Generate compact RGBI ordered-dither pairs using only Python's stdlib."""
from pathlib import Path

PALETTE = ((0,0,0),(0,0,170),(0,170,0),(0,170,170),
           (170,0,0),(170,0,170),(170,85,0),(170,170,170),
           (85,85,85),(85,85,255),(85,255,85),(85,255,255),
           (255,85,85),(255,85,255),(255,255,85),(255,255,255))
WEIGHTS = (2,4,1)

def best_pair(rgb):
    # Minimize the error of a 4x4 tile's mean, with a small penalty for
    # high-contrast noise. Integer arithmetic makes regeneration reproducible.
    best, result = None, 0
    for first, a in enumerate(PALETTE):
        for second in range(first,16):
            b = PALETTE[second]
            diff = tuple(b[c]-a[c] for c in range(3))
            length = sum(WEIGHTS[c]*diff[c]*diff[c] for c in range(3))
            projection = sum(WEIGHTS[c]*(rgb[c]-a[c])*diff[c] for c in range(3))
            # The noise penalty is 1/20 of the within-tile variance.
            # Its derivative changes the optimum mixture slightly. Check both
            # integer neighbors, including the single-colour endpoints.
            denominator = 19*length
            numerator = 320*projection-8*length
            fraction = max(0,min(16,numerator//denominator)) if denominator else 0
            for count in (fraction,min(16,fraction+1)):
                error = 20*sum(WEIGHTS[c]*(16*rgb[c]-16*a[c]-count*diff[c])**2 for c in range(3))
                error += length*count*(16-count)
                if best is None or error < best:
                    best = error
                    result = second if count == 16 else first | (second << 4) | (count << 8)
    return result

def clamp(n): return max(0,min(255,n))

def ycc_rgb(y,cb,cr):
    cb-=128; cr-=128
    # ITU-R BT.601 full-range JPEG conversion, rounded using integer weights.
    return (clamp(y+((91881*cr+32768)>>16)),
            clamp(y-((22554*cb+46802*cr+32768)>>16)),
            clamp(y+((116130*cb+32768)>>16)))

rgb = [best_pair((r*17,g*17,b*17)) for r in range(16) for g in range(16) for b in range(16)]
# Chroma cell 8 includes the exact neutral value 128. Keeping it neutral
# prevents grayscale JPEGs from acquiring a colour cast.
chroma = [128 if c == 8 else c*16+8 for c in range(16)]
ycc = [best_pair(ycc_rgb(y*17,chroma[cb],chroma[cr]))
       for y in range(16) for cb in range(16) for cr in range(16)]
output = Path(__file__).resolve().parents[1]/'src/TandyDither.inc'
with output.open('w') as f:
    f.write('// Generated by tools/generate-tandy-dither.py. Two RGBI indices and\n')
    f.write('// a 4-bit coverage count per 4x4 tile; 8192 bytes per table.\n')
    for name,table in (('tandyRGBDitherPairs',rgb),('tandyYCCDitherPairs',ycc)):
        f.write('const uint16_t '+name+'[4096] = {\n')
        for start in range(0,4096,16):
            f.write('    '+', '.join('0x%03x'%v for v in table[start:start+16])+',\n')
        f.write('};\n')
print(output)
